const tex = (s) => String(s).replace(/[\\&%$#_{}~^]/g, (c) => `\\${c}`);
const write = (name, body) => writeFileSync(new URL(name, OUT), `% Generated by scripts/report-data.mjs. Do not edit.\n${body}\n`);

// Same colors as the website (ui.js processColor), converted to hex for xcolor.
function processHex(index) {
  const hue = Math.round((index * 137.508) % 360);
  const s = 0.8;
  const l = 0.72;
  const k = (n) => (n + hue / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
}

function colorDefs(processes) {
  return processes.map((p, i) => `\\definecolor{pc-${tex(p.id)}}{HTML}{${processHex(i)}}`).join('\n');
}

// One Gantt row as TikZ commands. rows: [{ label, segments: [{pid, start, end, sliceIndex}] }]
function tikzGantt(rows, processes, { showSlices = false, maxWidthCm = 13 } = {}) {
  const end = Math.max(...rows.map((r) => r.segments[r.segments.length - 1].end));
  const u = Math.min(0.8, maxWidthCm / end);
  const lines = [colorDefs(processes), `\\begin{tikzpicture}[x=${u.toFixed(3)}cm, y=1cm, font=\\footnotesize]`];
  rows.forEach((row, r) => {
    const y = -r * 1.15;
    if (row.label) lines.push(`\\node[anchor=east, font=\\footnotesize\\bfseries] at (-0.3/${u.toFixed(3)}, ${y + 0.3}) {${tex(row.label)}};`);
    const ticks = new Set([0]);
    for (const s of row.segments) {
      ticks.add(s.start);
      ticks.add(s.end);
      const idle = s.pid === null;
      const fill = idle ? 'pattern=north east lines, pattern color=black!35' : `fill=pc-${tex(s.pid)}`;
      const name = idle ? '\\textit{idle}' : tex(s.pid);
      const slice = (row.showSlices ?? showSlices) && !idle && s.sliceIndex !== undefined ? `\\\\[-2pt]{\\tiny\\#${s.sliceIndex + 1}}` : '';
      lines.push(`\\draw[${fill}, draw=black!70] (${s.start}, ${y}) rectangle (${s.end}, ${y + 0.6});`);
      lines.push(`\\node[align=center, inner sep=0pt] at (${(s.start + s.end) / 2}, ${y + 0.3}) {${name}${slice}};`);
    }
    for (const t of [...ticks].sort((a, b) => a - b)) {
      lines.push(`\\draw (${t}, ${y}) -- (${t}, ${y - 0.08}) node[below, inner sep=1pt, font=\\scriptsize] {${t}};`);
    }
  });
  lines.push('\\end{tikzpicture}');
  return lines.join('\n');
}

// Hand segments [[pid, start, end]] → segment objects; RR slices numbered per process.
function handSegments(entry) {
  const count = new Map();
  return entry.segments.map(([pid, start, end]) => {
    const p = pid === 'idle' ? null : pid;
    const sliceIndex = p === null ? undefined : (count.get(p) ?? 0);
    if (p !== null) count.set(p, sliceIndex + 1);
    return { pid: p, start, end, sliceIndex };
  });
}

const segList = (segments) => segments.map((s) => `${s.pid === null ? 'idle' : s.pid}[${s.start},${s.end})`).join(' ');
const sameSegments = (a, b) => a.length === b.length && a.every((s, i) => s.pid === b[i].pid && s.start === b[i].start && s.end === b[i].end);
const fraction = (v) => (typeof v === 'string' && v.includes('/') ? v.split('/').map(Number) : [Number(v), 1]);
const sameFraction = ([a, b], { num, den }) => a * den === b * num;

// ---- Worked examples: hand vs simulator ----
function workedExample(key) {
  const entry = hand[key];
  const w = WORKLOADS[entry.workload];
  const ps = w.processes;
  const r = simulate(ps, entry.algorithm, entry.quantum);
  const hs = handSegments(entry);
  const rr = entry.algorithm === 'RR';
  const diffs = [];
  if (!sameSegments(hs, r.segments)) diffs.push('Gantt segments');

  const rows = r.metrics.map((m) => {
    const hm = entry.metrics[m.pid];
    const cells = METRICS.map(([k]) => {
      if (hm[k] !== m[k]) diffs.push(`${m.pid} ${k}`);
      return `${hm[k]} & ${hm[k] === m[k] ? m[k] : `\\textcolor{red}{${m[k]}}`}`;
    });
    const p = ps.find((x) => x.id === m.pid);
    return `${tex(m.pid)} & ${p.arrival} & ${p.burst} & ${cells.join(' & ')} \\\\`;
  });
  const avgCells = AVERAGES.map((k) => {
    const hv = fraction(entry.averages[k]);
    const ok = sameFraction(hv, r.averages[k]);
    if (!ok) diffs.push(`average ${k}`);
    return `\\multicolumn{2}{c}{${entry.averages[k]}${ok ? '' : ` vs ${r.averages[k].num}/${r.averages[k].den}`}}`;
  });
  const checks = verifySchedule(ps, r);
  const passed = checks.filter((c) => c.pass).length;

  const body = [
    '\\par\\noindent\\begin{minipage}{\\linewidth}',
    '\\begin{center}',
    tikzGantt([{ label: 'Hand', segments: hs }, { label: 'Simulator', segments: r.segments }], ps, { showSlices: rr }),
    '\\end{center}',
    '\\begin{center}\\small\\setlength{\\tabcolsep}{4pt}',
    '\\begin{tabular}{lcc' + 'cc'.repeat(METRICS.length) + '}',
    '\\toprule',
    ` & & & ${METRICS.map(([, l]) => `\\multicolumn{2}{c}{${l}}`).join(' & ')} \\\\`,
    METRICS.map((_, i) => `\\cmidrule(lr){${4 + 2 * i}-${5 + 2 * i}}`).join(' '),
    `Proc. & Arr. & Burst & ${METRICS.map(() => 'H & S').join(' & ')} \\\\`,
    '\\midrule',
    ...rows,
    '\\midrule',
    `\\multicolumn{7}{l}{Average (exact fractions)} & ${avgCells.join(' & ')} \\\\`,
    '\\bottomrule',
    '\\end{tabular}',
    '\\end{center}',
    '\\noindent\\textbf{Comparison.} ' + (diffs.length === 0
      ? `Hand (H) and simulator (S) agree on all ${hs.length} Gantt segments, all ${ps.length * METRICS.length} per-process values and the 3 averages (${AVERAGES.map((k) => `${k} ${formatAverage(r.averages[k])}`).join(', ')}). No discrepancy. The simulator's 5 invariants: ${passed}/5 pass.`
      : `\\textcolor{red}{Differences: ${tex(diffs.join(', '))}.} Simulator: ${tex(segList(r.segments))}.`),
    '\\end{minipage}\\par\\medskip',
  ];
  write(`case-${key}.tex`, body.join('\n'));
  return { key, diffs, r };
}

// ---- Input tables ----
function inputTable(key) {
  const ps = WORKLOADS[key].processes;
  write(`input-${key}.tex`, [
    '\\begin{tabular}{lcc}', '\\toprule', 'Process & Arrival & CPU burst \\\\', '\\midrule',
    ...ps.map((p) => `${tex(p.id)} & ${p.arrival} & ${p.burst} \\\\`), '\\bottomrule', '\\end{tabular}',
  ].join('\n'));
}

// Process switches: consecutive non-idle segments of different processes (idle in between does not count).
function switches(segments) {
  const run = segments.filter((s) => s.pid !== null);
  return run.slice(1).filter((s, i) => s.pid !== run[i].pid).length;
}

// ---- Compare all + stacked Gantts (Q1) ----
function compareAll(key) {
  const ps = WORKLOADS[key].processes;
  const results = ALGOS.map((a) => ({ a, r: simulate(ps, a, a === 'RR' ? 2 : null) }));
  const best = Object.fromEntries(AVERAGES.map((k) => [k, Math.min(...results.map(({ r }) => r.averages[k].num))]));
  const cell = (r, k) => (r.averages[k].num === best[k] ? `\\textbf{${formatAverage(r.averages[k])}}` : formatAverage(r.averages[k]));
  write(`compare-${key}.tex`, [
    '\\begin{tabular}{lcccc}', '\\toprule', 'Algorithm & Avg turnaround & Avg waiting & Avg response & Switches \\\\', '\\midrule',
    ...results.map(({ a, r }) => `${a === 'RR' ? 'RR ($q=2$)' : a} & ${AVERAGES.map((k) => cell(r, k)).join(' & ')} & ${switches(r.segments)} \\\\`),
    '\\bottomrule', '\\end{tabular}',
  ].join('\n'));
  write(`stack-${key}.tex`, tikzGantt(results.map(({ a, r }) => ({ label: a === 'RR' ? 'RR q=2' : a, segments: r.segments, showSlices: a === 'RR' })), ps));
}

// ---- RR quantum sweep (Q2) ----
function rrSweep() {
  const lines = ['\\begin{tabular}{llccccc}', '\\toprule',
    'Workload & $q$ & Avg turnaround & Avg waiting & Avg response & Slices & Switches \\\\', '\\midrule'];
  for (const key of ['A', 'B']) {
    const ps = WORKLOADS[key].processes;
    for (const q of [1, 2, 4]) {
      const r = simulate(ps, 'RR', q);
      lines.push(`${q === 1 ? key : ''} & ${q} & ${AVERAGES.map((k) => formatAverage(r.averages[k])).join(' & ')} & ${r.segments.filter((s) => s.pid !== null).length} & ${switches(r.segments)} \\\\`);
    }
    if (key === 'A') lines.push('\\midrule');
  }
  lines.push('\\bottomrule', '\\end{tabular}');
  write('rr-sweep.tex', lines.join('\n'));
  // Two equal jobs: the smallest case where a smaller quantum makes turnaround worse.
  const equal = [{ id: 'P1', arrival: 0, burst: 2 }, { id: 'P2', arrival: 0, burst: 2 }];
  write('rr-equal.tex', [1, 2].map((q) => {
    const r = simulate(equal, 'RR', q);
    return `\\item $q=${q}$: \\texttt{${tex(segList(r.segments))}}, average turnaround ${formatAverage(r.averages.turnaround)}, average response ${formatAverage(r.averages.response)}.`;
  }).join('\n'));
  for (const q of [1, 4]) {
    write(`rr-A-q${q}.tex`, tikzGantt([{ label: `RR q=${q}`, segments: simulate(WORKLOADS.A.processes, 'RR', q).segments }], WORKLOADS.A.processes, { showSlices: true }));
  }
}

// ---- Own tests T1–T7 ----
function tCases() {
  const lines = ['\\begin{tabular}{@{}l >{\\raggedright\\arraybackslash}p{3.7cm} l >{\\raggedright\\arraybackslash}p{3.9cm} c@{}}', '\\toprule',
    'Test & Behavior checked & Input (arrival, burst) & Expected Gantt (spec) & Actual \\\\', '\\midrule'];
  const out = [];
  for (const key of ['T1', 'T2', 'T3', 'T4', 'T5', 'T6', 'T7']) {
    const w = WORKLOADS[key];
    const q = w.algorithm === 'RR' ? w.quantum : null;
    const r = simulate(w.processes, w.algorithm, q);
    const expected = T_EXPECTED[key].map(([pid, start, end]) => ({ pid, start, end }));
    const ok = sameSegments(expected, r.segments);
    out.push({ key, ok });
    const input = w.processes.map((p) => `${tex(p.id)}(${p.arrival},${p.burst})`).join(' ');
    lines.push(`${key} & ${tex(w.checks)} & ${input}, ${w.algorithm}${q ? ` $q=${q}$` : ''} & \\texttt{${tex(segList(expected))}} & ${ok ? '\\checkmark' : '\\textcolor{red}{differs}'} \\\\`);
  }
  lines.push('\\bottomrule', '\\end{tabular}');
  write('tcases.tex', lines.join('\n'));
  for (const key of ['T1', 'T2', 'T3']) {
    const w = WORKLOADS[key];
    write(`gantt-${key}.tex`, tikzGantt([{ label: 'Simulator', segments: simulate(w.processes, w.algorithm, null).segments }], w.processes, { maxWidthCm: 9 }));
  }
  return out;
}

// ---- Test-suite numbers ----
function testStats() {
  const run = spawnSync(process.execPath, ['--test', '--test-reporter=tap'], { cwd: ROOT, encoding: 'utf8' });
  const num = (name) => Number((run.stdout.match(new RegExp(`^# ${name} (\\d+)`, 'm')) || [])[1]);
  const stats = { tests: num('tests'), pass: num('pass'), fail: num('fail'), skipped: num('skipped') };
  write('stats.tex', Object.entries(stats).map(([k, v]) => `\\newcommand{\\stat${k}}{${v}}`).join('\n'));
  return stats;
}

