const cases = ['A-FCFS', 'A-SJF', 'A-SRTF', 'A-RR2', 'B-FCFS', 'B-SJF', 'B-SRTF', 'B-RR2'].map(workedExample);
compareAll('A');
compareAll('B');
rrSweep();
const tc = tCases();
const stats = testStats();
