// Bundles src/ into one self-contained ./index.html (PLAN.md §6): inline CSS, one classic
// <script> IIFE, no modules, so it runs from file:// in Safari and Chrome. Zero dependencies.
// The module rules are enforced here; anything else makes the build fail loudly.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const MODULE_ORDER = ['limits', 'format', 'validate', 'scheduler', 'verify', 'workloads', 'ui'];
// Exposed as window.CPUScheduler for console demos and for build.test.js.
export const PUBLIC_API = ['ALGORITHMS', 'simulate', 'validateInput', 'toProcesses', 'verifySchedule', 'WORKLOADS', 'formatAverage'];

const ROOT = new URL('../', import.meta.url);
const IMPORT_LINE = /^import \{ ([A-Za-z_$][\w$]*(?:, [A-Za-z_$][\w$]*)*) \} from '\.\/([a-z]+)\.js';$/;
const EXPORT_LINE = /^export (?:function|const) ([A-Za-z_$][\w$]*)/;
const TOP_DECL = /^(?:async )?(?:function\*?|const|let|var|class) ([A-Za-z_$][\w$]*)/;

/** sources: { moduleName: text }. Returns the bundled script body (modules in `order`, one shared scope). */
export function bundleModules(sources, order = MODULE_ORDER) {
  const exportsOf = new Map();
  const declaredAt = new Map();
  const parts = [];
  for (const name of order) {
    const text = sources[name];
    if (text === undefined) throw new Error(`build: missing module src/${name}.js`);
    const exported = new Set();
    const out = [];
    text.split(/\r?\n/).forEach((line, i) => {
      const where = `src/${name}.js:${i + 1}`;
      const imp = IMPORT_LINE.exec(line);
      if (imp) {
        const [, names, from] = imp;
        if (!exportsOf.has(from)) {
          throw new Error(`build: ${where} imports from "${from}", which is not bundled before "${name}" (order: ${order.join(', ')})`);
        }
        for (const n of names.split(', ')) {
          if (!exportsOf.get(from).has(n)) throw new Error(`build: ${where} imports "${n}", but src/${from}.js does not export it`);
        }
        return; // dropped: all modules share one scope
      }
      if (/^\s*import\b/.test(line) || /\bimport\s*\(/.test(line) || /\bimport\.meta\b/.test(line)) {
        throw new Error(`build: ${where} uses an unsupported import form: ${line.trim()}`);
      }
      let code = line;
      const exp = EXPORT_LINE.exec(line);
      if (exp) {
        exported.add(exp[1]);
        code = line.slice('export '.length);
      } else if (/^\s*export\b/.test(line)) {
        throw new Error(`build: ${where} uses an unsupported export form: ${line.trim()} (only "export function" / "export const")`);
      }
      if (/^(?:const|let|var) [[{]/.test(code)) throw new Error(`build: ${where}: top-level destructuring is not supported`);
      const decl = TOP_DECL.exec(code);
      if (decl) {
        if (declaredAt.has(decl[1])) {
          throw new Error(`build: top-level name "${decl[1]}" at ${where} is already declared at ${declaredAt.get(decl[1])}`);
        }
        declaredAt.set(decl[1], where);
      }
      out.push(code);
    });
    exportsOf.set(name, exported);
    parts.push(`// ---- src/${name}.js ----\n${out.join('\n')}`);
  }
  return parts.join('\n\n');
}

export function buildHtml(template, css, script) {
  for (const marker of ['<!-- STYLE -->', '<!-- SCRIPT -->']) {
    if (template.split(marker).length !== 2) throw new Error(`build: the template must contain ${marker} exactly once`);
  }
  if (/<\/script/i.test(script)) throw new Error('build: the bundled script contains "</script", which would end the inline script early');
  if (/<\/style/i.test(css)) throw new Error('build: style.css contains "</style"');
  const js = [
    '<script>',
    '// Generated by scripts/build.mjs from src/. Do not edit this file; edit src/ and rebuild.',
    '(function () {',
    "'use strict';",
    script,
    '',
    `if (typeof window !== 'undefined') window.CPUScheduler = { ${PUBLIC_API.join(', ')} };`,
    '})();',
    '</script>',
  ].join('\n');
  // Function replacers, so "$" sequences in the code are inserted literally.
  return template.replace('<!-- STYLE -->', () => `<style>\n${css}</style>`).replace('<!-- SCRIPT -->', () => js);
}

const readSrc = (file) => readFileSync(new URL(`src/${file}`, ROOT), 'utf8').replace(/\r\n/g, '\n');

export function buildFromDisk() {
  const sources = Object.fromEntries(MODULE_ORDER.map((m) => [m, readSrc(`${m}.js`)]));
  return buildHtml(readSrc('index.template.html'), readSrc('style.css'), bundleModules(sources));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = buildFromDisk();
  writeFileSync(new URL('index.html', ROOT), html);
  console.log(`Wrote index.html (${(html.length / 1024).toFixed(1)} KB)`);
}
